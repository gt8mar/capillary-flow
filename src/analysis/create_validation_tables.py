"""
Create validation tables for the current CRI analysis.

The CRI source is results/Stiffness/cri_metrics.csv, generated by
src/analysis/stiffness_coeff.py. This file contains the active paper CRI:
AUC of the averaged up/down log-velocity curve from 0.2 to 1.2 psi.

Outputs are written to results/validation tables.
"""

from pathlib import Path

import numpy as np
import pandas as pd
import scipy.stats as stats
import statsmodels.api as sm
import statsmodels.formula.api as smf


REPO_ROOT = Path(__file__).resolve().parents[2]
INPUT_PATH = REPO_ROOT / "results" / "Stiffness" / "cri_metrics.csv"
OUTPUT_DIR = REPO_ROOT / "results" / "validation tables"
CONTROL_SET = "set01"
CRI_COL = "CRI"


def _iqr(values: pd.Series) -> float:
    return float(values.quantile(0.75) - values.quantile(0.25))


def _summary_row(label: str, age_rule: str, group: pd.DataFrame) -> dict:
    cri = group[CRI_COL].dropna()
    return {
        "group": label,
        "age_rule": age_rule,
        "n": int(len(cri)),
        "median_cri": float(cri.median()) if len(cri) else np.nan,
        "q1_cri": float(cri.quantile(0.25)) if len(cri) else np.nan,
        "q3_cri": float(cri.quantile(0.75)) if len(cri) else np.nan,
        "iqr_cri": _iqr(cri) if len(cri) else np.nan,
        "mean_cri": float(cri.mean()) if len(cri) else np.nan,
        "sd_cri": float(cri.std(ddof=1)) if len(cri) > 1 else np.nan,
        "min_age": float(group["Age"].min()) if len(group) else np.nan,
        "max_age": float(group["Age"].max()) if len(group) else np.nan,
    }


def load_controls() -> pd.DataFrame:
    if not INPUT_PATH.exists():
        raise FileNotFoundError(f"Missing CRI input: {INPUT_PATH}")

    df = pd.read_csv(INPUT_PATH)
    required = ["Participant", CRI_COL, "Age", "Sex", "SYS_BP", "SET"]
    missing = [col for col in required if col not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns in {INPUT_PATH}: {missing}")

    controls = df[df["SET"].eq(CONTROL_SET)].copy()
    for col in [CRI_COL, "Age", "SYS_BP"]:
        controls[col] = pd.to_numeric(controls[col], errors="coerce")
    controls["Sex"] = controls["Sex"].astype(str).str.strip()
    controls = controls.replace({"Sex": {"": np.nan, "nan": np.nan, "None": np.nan}})
    controls = controls.dropna(subset=[CRI_COL, "Age", "Sex", "SYS_BP"])
    controls = controls.sort_values(["Age", "Participant"]).reset_index(drop=True)

    if len(controls) != 35:
        raise ValueError(f"Expected controls n=35, found n={len(controls)}")

    return controls


def make_binary_age_split_table(controls: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    summary_rows = []
    test_rows = []

    for threshold in [30, 50, 60]:
        lower = controls[controls["Age"] < threshold]
        upper = controls[controls["Age"] >= threshold]
        summary_rows.append(
            _summary_row(f"<{threshold}", f"Age < {threshold}", lower)
            | {"threshold": threshold, "interval": f"[0,{threshold})"}
        )
        summary_rows.append(
            _summary_row(f">={threshold}", f"Age >= {threshold}", upper)
            | {"threshold": threshold, "interval": f"[{threshold},inf)"}
        )

        stat, p_value = stats.mannwhitneyu(
            lower[CRI_COL], upper[CRI_COL], alternative="two-sided"
        )
        test_rows.append(
            {
                "comparison": f"<{threshold} vs >={threshold}",
                "threshold": threshold,
                "test": "Mann-Whitney U",
                "n_lower": int(len(lower)),
                "n_upper": int(len(upper)),
                "statistic": float(stat),
                "p_value": float(p_value),
            }
        )

    return pd.DataFrame(summary_rows), pd.DataFrame(test_rows)


def make_age_bracket_tables(controls: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    bins = [0, 30, 50, 60, 70, np.inf]
    labels = ["<30", "30-49", "50-59", "60-69", "70+"]
    intervals = ["[0,30)", "[30,50)", "[50,60)", "[60,70)", "[70,inf)"]
    controls = controls.copy()
    controls["age_bracket"] = pd.cut(
        controls["Age"], bins=bins, labels=labels, right=False, include_lowest=True
    )

    summary_rows = []
    for label, interval in zip(labels, intervals):
        group = controls[controls["age_bracket"].eq(label)]
        summary_rows.append(_summary_row(label, f"Age in {interval}", group) | {"interval": interval})

    reference = controls[controls["age_bracket"].eq("<30")][CRI_COL]
    test_rows = []
    for label in labels[1:]:
        group = controls[controls["age_bracket"].eq(label)][CRI_COL]
        if len(reference) and len(group):
            stat, p_value = stats.mannwhitneyu(reference, group, alternative="two-sided")
            test_rows.append(
                {
                    "comparison": f"<30 vs {label}",
                    "test": "Mann-Whitney U",
                    "n_reference": int(len(reference)),
                    "n_group": int(len(group)),
                    "statistic": float(stat),
                    "p_value": float(p_value),
                }
            )

    return pd.DataFrame(summary_rows), pd.DataFrame(test_rows)


def make_model_tables(controls: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    model = smf.ols("CRI ~ Age + C(Sex) + SYS_BP", data=controls).fit()
    anova = sm.stats.anova_lm(model, typ=2).reset_index(names="factor")
    anova["model"] = "CRI ~ Age + C(Sex) + SYS_BP"
    anova["n"] = int(model.nobs)
    anova["r_squared"] = float(model.rsquared)
    anova["adj_r_squared"] = float(model.rsquared_adj)

    conf = model.conf_int()
    coefficient_rows = []
    for term in model.params.index:
        coefficient_rows.append(
            {
                "term": term,
                "estimate": float(model.params[term]),
                "std_error": float(model.bse[term]),
                "t": float(model.tvalues[term]),
                "p_value": float(model.pvalues[term]),
                "ci_low": float(conf.loc[term, 0]),
                "ci_high": float(conf.loc[term, 1]),
                "model": "CRI ~ Age + C(Sex) + SYS_BP",
                "n": int(model.nobs),
                "r_squared": float(model.rsquared),
                "adj_r_squared": float(model.rsquared_adj),
            }
        )

    return anova, pd.DataFrame(coefficient_rows)


def write_readme() -> None:
    text = """Validation Tables
=================

Data source: results/Stiffness/cri_metrics.csv
CRI version: active paper CRI from src/analysis/stiffness_coeff.py.
Definition: AUC of the averaged up/down log-velocity curve from 0.2 to 1.2 psi.
Control cohort: SET == 'set01'; required complete-control n = 35.

Age split rules:
- Binary threshold tables use Age < threshold and Age >= threshold.
- Bracket table uses left-closed/right-open bins:
  [0,30), [30,50), [50,60), [60,70), [70,inf).
- This means age 30 is in 30-49, age 50 is in 50-59, age 60 is in 60-69,
  and age 70 is in 70+.
"""
    (OUTPUT_DIR / "README.txt").write_text(text, encoding="utf-8")


def main() -> int:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    controls = load_controls()

    controls.to_csv(OUTPUT_DIR / "control_participants_cri_validation.csv", index=False)

    binary_summary, binary_tests = make_binary_age_split_table(controls)
    binary_summary.to_csv(OUTPUT_DIR / "control_cri_binary_age_split_summary.csv", index=False)
    binary_tests.to_csv(OUTPUT_DIR / "control_cri_binary_age_split_tests.csv", index=False)

    bracket_summary, bracket_tests = make_age_bracket_tables(controls)
    bracket_summary.to_csv(OUTPUT_DIR / "control_cri_age_bracket_summary.csv", index=False)
    bracket_tests.to_csv(OUTPUT_DIR / "control_cri_age_bracket_tests_vs_under30.csv", index=False)

    anova, coefficients = make_model_tables(controls)
    anova.to_csv(OUTPUT_DIR / "control_cri_predictor_anova.csv", index=False)
    coefficients.to_csv(OUTPUT_DIR / "control_cri_predictor_coefficients.csv", index=False)

    write_readme()

    print(f"Wrote validation tables to: {OUTPUT_DIR}")
    print(f"Controls n: {len(controls)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
